TEST(TlsHandshake, TheSystemTrustStoreDoesNotTrustAPrivateCa) {
  const TestServer server(TestServer::Mode::kTls);
  EXPECT_EQ(Connect(Config(server, "")).error_code(), grpc::StatusCode::UNAVAILABLE);
}

TEST(TlsHandshake, ANonPemCaIsAnErrorNotACrash) {
  const TestServer server(TestServer::Mode::kTls);
  EXPECT_EQ(Connect(Config(server, "certs/ca.pem")).error_code(), grpc::StatusCode::UNAVAILABLE);
}

TEST(TlsHandshake, CrlfPemsCompleteTheMutualTlsHandshake) {
  const TestServer server(TestServer::Mode::kMutualTls);
  const Pki& pki = TestPki::Get().own;
  ASSERT_NE(ToCrlf(pki.client_key).find("\r\n"), std::string::npos);
  EXPECT_TRUE(Connect(Config(server, ToCrlf(pki.ca), ToCrlf(pki.client_cert), ToCrlf(pki.client_key))).ok());
}

TEST(TlsHandshake, TheServerNameIsVerifiedAndCanBeOverridden) {
  const TestServer server(TestServer::Mode::kTls);
  const ClientConfig config = Config(server, TestPki::Get().own.ca);
  for (const auto& [name, expected] : std::map<std::string, grpc::StatusCode>{
           {"localhost", grpc::StatusCode::OK}, {"nlu.example.com", grpc::StatusCode::UNAVAILABLE}}) {
    grpc::ChannelArguments args = ondewo::client::DefaultChannelArguments();
    args.SetSslTargetNameOverride(name);
    std::shared_ptr<grpc::Channel> channel;
    EXPECT_TRUE(ondewo::client::CreateChannel(config, args, &channel).ok());
    EXPECT_EQ(Check(channel).error_code(), expected) << name;
  }
}

TEST(TlsHandshake, ABareIpv6LiteralHostConnects) {
  const TestServer server(TestServer::Mode::kMutualTls, "[::1]:0");
  if (server.port == 0) GTEST_SKIP() << "no IPv6 loopback in this environment";
  const Pki& pki = TestPki::Get().own;
  EXPECT_TRUE(Connect(Config(server, pki.ca, pki.client_cert, pki.client_key, "::1")).ok());
}

TEST(TlsHandshake, AnInsecureChannelWarnsNamingHostAndPort) {
  const TestServer server(TestServer::Mode::kInsecure);
  ClientConfig config = Config(server, "");
  config.use_secure_channel = false;
  std::ostringstream captured;
  std::streambuf* const original = std::clog.rdbuf(captured.rdbuf());
  const grpc::Status status = Connect(config);
  std::clog.rdbuf(original);
  EXPECT_TRUE(status.ok()) << status.error_message();
  EXPECT_NE(captured.str().find("INSECURE"), std::string::npos) << captured.str();
  EXPECT_NE(captured.str().find("127.0.0.1:" + config.port), std::string::npos) << captured.str();
}

