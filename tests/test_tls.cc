TEST(TlsConfig, HostAndPortBracketsBareIpv6LiteralsOnly) {
  ClientConfig config;
  config.port = "50051";
  const std::map<std::string, std::string> expected = {
      {"localhost", "localhost:50051"},
      {"10.0.0.5", "10.0.0.5:50051"},
      {"::1", "[::1]:50051"},
      {"2001:db8::17", "[2001:db8::17]:50051"},
      {"::ffff:10.0.0.5", "[::ffff:10.0.0.5]:50051"},
      {"fe80::1%eth0", "[fe80::1%eth0]:50051"},
      {"[::1]", "[::1]:50051"},
      {"ipv6:[::1]", "ipv6:[::1]:50051"},
      {"dns:///nlu.example.com", "dns:///nlu.example.com:50051"},
      {"cafe", "cafe:50051"},
  };
  for (const auto& [host, host_and_port] : expected) {
    config.host = host;
    EXPECT_EQ(config.HostAndPort(), host_and_port) << host;
  }
}

TEST(TlsConfig, ToStringRedactsTheKeyAndPrintsNoPem) {
  ClientConfig config;
  config.host = "nlu.example.com";
  config.port = "443";
  config.grpc_cert = "-----BEGIN CERTIFICATE-----ca-cert-content";
  config.grpc_client_cert = kFakeCert;
  config.grpc_client_key = kFakeKey;
  const std::string text = config.ToString();
  EXPECT_NE(text.find("grpc_client_key=***REDACTED***"), std::string::npos) << text;
  EXPECT_NE(text.find("nlu.example.com"), std::string::npos) << text;
  ExpectNoSecret(text);
  std::ostringstream streamed;
  streamed << config;
  EXPECT_EQ(streamed.str(), text);
}

TEST(TlsConfig, ToStringRendersAnEmptyKeyEmpty) {
  ClientConfig config;
  config.use_secure_channel = false;
  const std::string text = config.ToString();
  EXPECT_NE(text.find("grpc_client_key=,"), std::string::npos) << text;
  EXPECT_EQ(text.find("REDACTED"), std::string::npos) << text;
  EXPECT_NE(text.find("use_secure_channel=false"), std::string::npos) << text;
}

TEST(TlsConfig, HalfAClientIdentityIsRefusedBeforeGrpc) {
  for (const bool cert_only : {true, false}) {
    ClientConfig config;
    config.host = "::1";
    config.port = "50051";
    (cert_only ? config.grpc_client_cert : config.grpc_client_key) = cert_only ? kFakeCert : kFakeKey;
    std::shared_ptr<grpc::Channel> channel;
    const grpc::Status status = ondewo::client::CreateChannel(config, &channel);
    EXPECT_EQ(status.error_code(), grpc::StatusCode::INVALID_ARGUMENT);
    EXPECT_NE(status.error_message().find("only one of grpc_client_cert and grpc_client_key"), std::string::npos);
    EXPECT_NE(status.error_message().find("[::1]:50051"), std::string::npos) << status.error_message();
    ExpectNoSecret(status.error_message());
    EXPECT_EQ(channel, nullptr);
    std::shared_ptr<grpc::ChannelCredentials> credentials;
    EXPECT_FALSE(ondewo::client::CreateChannelCredentials(config, &credentials).ok());
    EXPECT_EQ(credentials, nullptr);
  }
}

TEST(TlsConfig, AnInsecureChannelWithAClientIdentityIsRefused) {
  ClientConfig config;
  config.host = "nlu.example.com";
  config.port = "50051";
  config.grpc_client_cert = kFakeCert;
  config.grpc_client_key = kFakeKey;
  config.use_secure_channel = false;
  std::shared_ptr<grpc::Channel> channel;
  const grpc::Status status = ondewo::client::CreateChannel(config, &channel);
  EXPECT_EQ(status.error_code(), grpc::StatusCode::INVALID_ARGUMENT);
  EXPECT_NE(status.error_message().find("use_secure_channel is false"), std::string::npos);
  EXPECT_NE(status.error_message().find("nlu.example.com:50051"), std::string::npos);
  ExpectNoSecret(status.error_message());
  EXPECT_EQ(channel, nullptr);
}

TEST(TlsConfig, DefaultChannelArgumentsMatchTheOtherSdks) {
  const grpc::ChannelArguments args = ondewo::client::DefaultChannelArguments();
  grpc_channel_args raw;
  args.SetChannelArgs(&raw);
  std::map<std::string, int> ints;
  for (size_t i = 0; i < raw.num_args; ++i)
    if (raw.args[i].type == GRPC_ARG_INTEGER) ints[raw.args[i].key] = raw.args[i].value.integer;
  const std::map<std::string, int> expected = {
      {GRPC_ARG_MAX_SEND_MESSAGE_LENGTH, 2147483647},
      {GRPC_ARG_MAX_RECEIVE_MESSAGE_LENGTH, 2147483647},
      {GRPC_ARG_KEEPALIVE_TIME_MS, 30000},
      {GRPC_ARG_KEEPALIVE_TIMEOUT_MS, 20000},
      {GRPC_ARG_KEEPALIVE_PERMIT_WITHOUT_CALLS, 0},
      {GRPC_ARG_HTTP2_MAX_PINGS_WITHOUT_DATA, 2},
      {"grpc.http2.ping_timeout_ms", 20000},
      {GRPC_ARG_MAX_RECONNECT_BACKOFF_MS, 5000},
  };
  for (const auto& [key, value] : expected) EXPECT_EQ(ints[key], value) << key;
}

