using ondewo::client::ClientConfig;

// The PEMs of one CA and the leaves it signed.
struct Pki {
  std::string ca;
  std::string server_cert;
  std::string server_key;
  std::string client_cert;
  std::string client_key;
};

std::string ReadFile(const std::filesystem::path& path) {
  std::ifstream in(path, std::ios::binary);
  return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

// Generated once per test process (CTest runs every TEST in a process of its own), with the
// same openssl commands the README documents.
class TestPki {
 public:
  static const TestPki& Get() {
    static const TestPki pki;
    return pki;
  }

  Pki own;
  Pki foreign;

 private:
  TestPki() {
    char dir_template[] = "/tmp/ondewo-tls-test-XXXXXX";
    const std::filesystem::path dir = mkdtemp(dir_template);
    std::ofstream(dir / "pki.sh") << R"(set -e
cd "$1"
ca() {
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 2 \
    -subj "/CN=$1" -keyout "$1.key" -out "$1.pem"
}
leaf() {
  printf "$4" > "$1.ext"
  openssl req -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes \
    -subj "/CN=$2" -keyout "$1.key" -out "$1.csr"
  openssl x509 -req -in "$1.csr" -CA "$3.pem" -CAkey "$3.key" -CAcreateserial -days 2 \
    -extfile "$1.ext" -out "$1.pem"
}
ca ca
ca foreign-ca
leaf server localhost ca 'subjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1\nextendedKeyUsage=serverAuth\n'
leaf client my-client ca 'extendedKeyUsage=clientAuth\n'
leaf foreign-client my-client foreign-ca 'extendedKeyUsage=clientAuth\n'
)";
    const std::string command = "sh " + (dir / "pki.sh").string() + " " + dir.string() + " > " +
                                (dir / "pki.log").string() + " 2>&1";
    EXPECT_EQ(std::system(command.c_str()), 0) << ReadFile(dir / "pki.log");
    own = {ReadFile(dir / "ca.pem"), ReadFile(dir / "server.pem"), ReadFile(dir / "server.key"),
           ReadFile(dir / "client.pem"), ReadFile(dir / "client.key")};
    foreign = {ReadFile(dir / "foreign-ca.pem"), "", "", ReadFile(dir / "foreign-client.pem"),
               ReadFile(dir / "foreign-client.key")};
    std::filesystem::remove_all(dir);
  }
};

// Answers every method with one empty message and OK, whatever the request. Generic, so the
// suite needs no service of its own and no generated type.
class AnswerEverything : public grpc::CallbackGenericService {
  grpc::ServerGenericBidiReactor* CreateReactor(grpc::GenericCallbackServerContext*) override {
    class Reactor : public grpc::ServerGenericBidiReactor {
     public:
      Reactor() { StartWriteAndFinish(&response_, grpc::WriteOptions(), grpc::Status::OK); }
      void OnDone() override { delete this; }

     private:
      grpc::Slice empty_{""};
      grpc::ByteBuffer response_{&empty_, 1};
    };
    return new Reactor;
  }
};

// An in-process server answering every method. TLS with the own PKI's server
// certificate, optionally requiring a client certificate signed by the own CA; or plaintext.
class TestServer {
 public:
  enum class Mode { kInsecure, kTls, kMutualTls };

  explicit TestServer(Mode mode, const std::string& address = "127.0.0.1:0") {
    const Pki& pki = TestPki::Get().own;
    grpc::SslServerCredentialsOptions options(mode == Mode::kMutualTls
                                                  ? GRPC_SSL_REQUEST_AND_REQUIRE_CLIENT_CERTIFICATE_AND_VERIFY
                                                  : GRPC_SSL_DONT_REQUEST_CLIENT_CERTIFICATE);
    options.pem_root_certs = pki.ca;
    options.pem_key_cert_pairs.push_back({pki.server_key, pki.server_cert});
    grpc::ServerBuilder builder;
    builder.RegisterCallbackGenericService(&service);
    builder.AddListeningPort(address,
                             mode == Mode::kInsecure ? grpc::InsecureServerCredentials()
                                                     : grpc::SslServerCredentials(options),
                             &port);
    server = builder.BuildAndStart();
  }

  ~TestServer() {
    if (server) server->Shutdown(std::chrono::system_clock::now());
  }

  // Declared before the server, so it outlives it.
  AnswerEverything service;
  int port = 0;
  std::unique_ptr<grpc::Server> server;
};

ClientConfig Config(const TestServer& server, const std::string& ca, const std::string& client_cert = "",
                    const std::string& client_key = "", const std::string& host = "127.0.0.1") {
  ClientConfig config;
  config.host = host;
  config.port = std::to_string(server.port);
  config.grpc_cert = ca;
  config.grpc_client_cert = client_cert;
  config.grpc_client_key = client_key;
  return config;
}

// One unary RPC; its status says whether the call reached the server.
grpc::Status Check(const std::shared_ptr<grpc::Channel>& channel) {
  grpc::GenericStub stub(channel);
  grpc::CompletionQueue queue;
  grpc::ClientContext context;
  context.set_deadline(std::chrono::system_clock::now() + std::chrono::seconds(10));
  grpc::Slice empty("");
  const grpc::ByteBuffer request(&empty, 1);
  grpc::ByteBuffer response;
  grpc::Status status;
  auto call = stub.PrepareUnaryCall(&context, "/ondewo.test.Tls/Check", request, &queue);
  call->StartCall();
  call->Finish(&response, &status, nullptr);
  void* tag = nullptr;
  bool ok = false;
  EXPECT_TRUE(queue.Next(&tag, &ok));
  queue.Shutdown();
  while (queue.Next(&tag, &ok)) continue;
  return status;
}

grpc::Status Connect(const ClientConfig& config) {
  std::shared_ptr<grpc::Channel> channel;
  const grpc::Status created = ondewo::client::CreateChannel(config, &channel);
  EXPECT_TRUE(created.ok()) << created.error_message();
  return Check(channel);
}

std::string ToCrlf(const std::string& pem) {
  std::string out;
  for (const char c : pem) out += c == '\n' ? std::string("\r\n") : std::string(1, c);
  return out;
}

// Stand-ins for PEM content in the tests that never reach gRPC. The key's marker is split into two
// literals so the detect-private-key pre-commit hook does not mistake this file for a key.
constexpr const char* kFakeCert = "-----BEGIN CERTIFICATE-----cert-content";
constexpr const char* kFakeKey = "-----BEGIN " "PRIVATE KEY-----key-content";

// No error message and no rendering may carry key or certificate material.
void ExpectNoSecret(const std::string& text) {
  EXPECT_EQ(text.find("BEGIN"), std::string::npos) << text;
  EXPECT_EQ(text.find("PRIVATE"), std::string::npos) << text;
  EXPECT_EQ(text.find("cert-content"), std::string::npos) << text;
  EXPECT_EQ(text.find("key-content"), std::string::npos) << text;
}

