// TLS / mutual TLS through ondewo/client/channel.h, against real in-process gRPC servers.
//
// Product-agnostic: nothing here names a generated type, so the file is copied verbatim
// between the ONDEWO C++ clients. Every handshake test issues a real RPC (the default health
// method, answered by a generic callback service): an OK answer proves the handshake completed,
// UNAVAILABLE that it was refused - and in neither case may the process crash.
//
// The PKI (a CA, a server certificate for localhost / 127.0.0.1 / ::1, a client certificate,
// and a second, unrelated CA with a client certificate of its own) is generated by the openssl
// CLI into a temporary directory at test time. No private key is committed.

